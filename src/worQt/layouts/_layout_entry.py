from __future__ import annotations

from typing import TYPE_CHECKING

from PySide6.QtWidgets import QWidget
from worktoy.desc import Field
from worktoy.dispatch import overload
from worktoy.waitaminute import MissingVariable, TypeException

from moreworktoy.mcls import BaseObject
from . import LayoutSpan

if TYPE_CHECKING:  # pragma: no cover
  from typing import Any, Self, TypeAlias

  Span: TypeAlias = LayoutSpan


class LayoutEntry(BaseObject):
  """
  LayoutEntry encapsulates an entry in WidgetLayout objects. It consists of
  a widget and a non-empty LayoutSpan.
  """

  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #
  #  NAMESPACE  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #
  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #

  #  Class Variables

  #  Fallback Variables

  #  Private Variables
  __widget_object__ = None
  __layout_span__ = None

  #  Public Variables
  widget = Field()
  span = Field()

  #  Virtual Variables

  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #
  #  GETTERS  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #
  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #

  @widget.GET
  def _getWidget(self, ) -> QWidget:
    if self.__widget_object__ is None:
      raise MissingVariable(self, 'widget', QWidget)
    if isinstance(self.__widget_object__, QWidget):
      return self.__widget_object__
    raise TypeException('__widget_object__', self.__widget_object__, QWidget)

  @span.GET
  def _getSpan(self, **kwargs) -> LayoutSpan:
    if self.__layout_span__ is None:
      if kwargs.get('_recursion', False):
        raise RecursionError
      self.__layout_span__ = LayoutSpan()
      return self._getSpan(_recursion=True)
    return self.__layout_span__

  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #
  #  SETTERS  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #
  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #

  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #
  #  SIGNALS  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #
  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #

  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #
  #  Python API   # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #
  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #

  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #
  #  CONSTRUCTORS   # # # # # # # # # # # # # # # # # # # # # # # # # # # # #
  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #

  @overload(QWidget, LayoutSpan)
  def __init__(self, widget: QWidget, span: Span) -> None:
    self.__widget_object__ = widget
    self.__layout_span__ = span

  @overload(LayoutSpan, QWidget)
  def __init__(self, span: LayoutSpan, widget: QWidget) -> None:
    self.__widget_object__ = widget
    self.__layout_span__ = span

  @overload(QWidget)
  def __init__(self, widget: QWidget) -> None:
    self.__widget_object__ = widget
    self.__layout_span__ = LayoutSpan()


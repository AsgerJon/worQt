  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #

  def addWidget(self, widget, *args) -> None:
    row, col, rowSpan, colSpan, *_ = [*args, None, None, None, None]
    row = maybe(row, 0)
    col = maybe(col, 0)
    rowSpan = maybe(rowSpan, 1)
    colSpan = maybe(colSpan, 1)
    return QGridLayout.addWidget(self, widget, row, col, rowSpan, colSpan)

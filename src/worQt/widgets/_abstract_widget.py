from __future__ import annotations

from typing import TYPE_CHECKING

from PySide6.QtGui import QShowEvent
from PySide6.QtWidgets import QWidget
from worktoy.dispatch import overload

from . import WidgetMixin
from ..utils import EmptyBrush, EmptyPen

if TYPE_CHECKING:  # pragma: no cover
  pass


class AbstractWidget(QWidget, WidgetMixin):
  """
  AbstractWidget provides the entry point for widgets.
  """

  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #
  #  NAMESPACE  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #
  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #

  #  Public Variables
  emptyPen = EmptyPen()
  emptyBrush = EmptyBrush()

  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #
  #  CONSTRUCTORS   # # # # # # # # # # # # # # # # # # # # # # # # # # # # #
  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #

  @overload(QWidget, strict=True)
  def __init__(self, parent: QWidget, **kwargs) -> None:
    QWidget.__init__(self, parent)

  @overload()
  def __init__(self, **kwargs) -> None:
    QWidget.__init__(self, )

  @overload.finalize
  def __init__(self, *args, **kwargs) -> None:
    pass

  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #
  #  OPTIONAL METHODS   # # # # # # # # # # # # # # # # # # # # # # # # # # #
  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #

  def initUI(self, ) -> None:
    """
    This method is invoked during 'showEvent' before the super call.
    Subclasses should implement this method rather than the 'showEvent'
    method if at all possible. The default implementation does nothing.
    """
    pass


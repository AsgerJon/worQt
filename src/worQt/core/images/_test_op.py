from torch.nn.functional import conv2d, max_pool2d, pad
from torch.nn import Conv2d
from worktoy.desc import Field
from worktoy.dispatch import overload

from . import OperatorProcedure


class TestOp(OperatorProcedure):
  """Test operation for image processing."""

  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #
  #  NAMESPACE  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #
  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #

  #  Class Variables

  #  Fallback Variables
  __fallback_size__ = 11
  __fallback_sigma__ = 1.
  #  Private Variables
  __kernel_size__ = None
  __gaussian_sigma__ = None

  #  Public Variables
  size = Field()
  sigma = Field()

  #  Virtual Variables

  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #
  #  GETTERS  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #
  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #

  @size.GET
  def _getSize(self, **kwargs) -> int:
    if self.__kernel_size__ is None:
      if kwargs.get('_recursion', False):
        raise RecursionError
      self.__kernel_size__ = self.__fallback_size__
      return self._getSize(_recursion=True)
    return self.__kernel_size__

  @sigma.GET
  def _getSigma(self, **kwargs) -> float:
    if self.__gaussian_sigma__ is None:
      if kwargs.get('_recursion', False):
        raise RecursionError
      self.__gaussian_sigma__ = self.__fallback_sigma__
      return self._getSigma(_recursion=True)
    return self.__gaussian_sigma__

  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #
  #  SETTERS  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #
  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #

  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #
  #  SIGNALS  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #
  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #

  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #
  #  Python API   # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #
  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #

  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #
  #  CONSTRUCTORS   # # # # # # # # # # # # # # # # # # # # # # # # # # # # #
  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #

  @overload(int, float)
  def __init__(self, size: int, sigma: float) -> None:
    self.__kernel_size__ = size
    self.__gaussian_sigma__ = sigma

  @overload(int)
  def __init__(self, size: int) -> None:
    self.__kernel_size__ = size

  @overload()
  def __init__(self, ) -> None:
    pass

  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #
  #  DOMAIN SPECIFIC  # # # # # # # # # # # # # # # # # # # # # # # # # # # #
  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #

  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #
  #  ABSTRACT METHODS   # # # # # # # # # # # # # # # # # # # # # # # # # # #
  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #

  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #
  #  OPTIONAL METHODS   # # # # # # # # # # # # # # # # # # # # # # # # # # #
  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #

  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #
  #  PARENT METHODS   # # # # # # # # # # # # # # # # # # # # # # # # # # # #
  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #

  def apply(self, imageData: Tensor, **kwargs) -> Tensor:
    return self._gaussianBlur(imageData, self.size, self.sigma)


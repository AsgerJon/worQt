  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #

  #  Class Variables
  __width_private_key__ = """__image_width__"""
  __height_private_key__ = """__image_height__"""

  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #
  #  PARENT METHODS   # # # # # # # # # # # # # # # # # # # # # # # # # # # #
  # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # # #

  def __instance_get__(self, *args, **kwargs) -> tuple[int, int]:
    w = getattr(self.instance, self.__width_private_key__)
    h = getattr(self.instance, self.__height_private_key__)
    return w, h


